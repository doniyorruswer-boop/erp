const DAY_NAME_LIST = ["Dushanba", "Seshanba", "Chorshanba", "Payshanba", "Juma", "Shanba"];

function formatDateKey(d) {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}

function formatDateString(d) {
  const day = String(d.getDate()).padStart(2, "0");
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const y = d.getFullYear();
  return `${day}.${m}.${y}`;
}

// Generates real school calendar weeks between start and end dates
export function generateWeeksForQuarter(startDateStr, endDateStr) {
  const [sY, sM, sD] = startDateStr.split("-").map(Number);
  const [eY, eM, eD] = endDateStr.split("-").map(Number);
  const startDate = new Date(sY, sM - 1, sD, 0, 0, 0);
  const endDate = new Date(eY, eM - 1, eD, 23, 59, 59);

  let currentMonday = new Date(startDate);
  const dayOfWeek = currentMonday.getDay();
  // If Sunday (0), Monday was 6 days ago (-6), else 1 - dayOfWeek
  const diffToMonday = dayOfWeek === 0 ? -6 : 1 - dayOfWeek;
  currentMonday.setDate(currentMonday.getDate() + diffToMonday);
  currentMonday.setHours(0, 0, 0, 0);

  const weeks = [];
  let weekNum = 1;

  while (currentMonday <= endDate) {
    const days = [];
    let hasAnyDayInQuarter = false;

    for (let i = 0; i < 6; i++) {
      const d = new Date(currentMonday);
      d.setDate(d.getDate() + i);

      const inQuarter = d >= startDate && d <= endDate;
      if (inQuarter) hasAnyDayInQuarter = true;

      const dateKey = formatDateKey(d);
      const dateString = formatDateString(d);
      const dateLabel = inQuarter ? `${d.getDate()}-${UZ_MONTH_NAMES[d.getMonth()]}` : "—";

      days.push({
        dayName: DAY_NAME_LIST[i],
        dateKey,
        dateLabel,
        dateString,
        inQuarter,
      });
    }

    if (hasAnyDayInQuarter) {
      const weekStartStr = formatDateString(currentMonday);
      const satDate = new Date(currentMonday);
      satDate.setDate(satDate.getDate() + 5);
      const weekEndStr = formatDateString(satDate);

      weeks.push({
        weekNumber: weekNum,
        weekLabel: `${weekNum}-hafta`,
        dateRangeText: `${weekStartStr} - ${weekEndStr}`,
        days,
      });
      weekNum++;
    }

    currentMonday.setDate(currentMonday.getDate() + 7);
  }

  return weeks;
}

