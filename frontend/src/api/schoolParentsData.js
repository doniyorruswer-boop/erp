const STORAGE_KEY = "crm_school_parents_v1";

export function loadSchoolParents() {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) {
      const initial = initialSchoolParents.map(p => ({ ...p, isActive: p.isActive !== false }));
      saveSchoolParents(initial);
      return initial;
    }
    const data = JSON.parse(raw);
    if (Array.isArray(data) && data.length) {
      const normalized = data.map(p => ({
        ...p,
        isActive: p.isActive !== undefined ? Boolean(p.isActive) : true
      }));
      return normalized;
    }
    const initial = initialSchoolParents.map(p => ({ ...p, isActive: p.isActive !== false }));
    return initial;
  } catch (e) {
    console.error("loadSchoolParents error:", e);
    return initialSchoolParents.map(p => ({ ...p, isActive: p.isActive !== false }));
  }
}

export function saveSchoolParents(list) {
  try {
    localStorage.setItem(STORAGE_KEY, JSON.stringify(list));
  } catch (e) {
    console.error("saveSchoolParents error:", e);
  }
}

export function addSchoolParent(parentData) {
  const list = loadSchoolParents();
  const id = "par-" + Date.now();
  const now = new Date();
  const pad = (n) => String(n).padStart(2, "0");
  const createdAt = `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;

  const newParent = {
    id,
    fullName: parentData.fullName.trim(),
    phone: parentData.phone.trim(),
    login: parentData.login ? parentData.login.trim() : generateLoginFromName(parentData.fullName),
    children: parentData.children || [],
    lastLogin: null,
    createdAt,
    status: "active",
    isActive: true,
    telegram: parentData.telegram || ""
  };

  list.unshift(newParent);
  saveSchoolParents(list);
  return newParent;
}

export function updateSchoolParent(id, updatedFields) {
  const list = loadSchoolParents();
  const idx = list.findIndex(p => p.id === id);
  if (idx !== -1) {
    list[idx] = { ...list[idx], ...updatedFields };
    saveSchoolParents(list);
    return list[idx];
  }
  return null;
}

export function deleteSchoolParent(id) {
  const list = loadSchoolParents();
  const filtered = list.filter(p => p.id !== id);
  saveSchoolParents(filtered);
  return filtered;
}

export function linkChildToParent(parentId, childObj) {
  const list = loadSchoolParents();
  const idx = list.findIndex(p => p.id === parentId);
  if (idx !== -1) {
    const parent = list[idx];
    if (!parent.children) parent.children = [];
    // Dublikat bo'lmasligi uchun tekshirish
    const exists = parent.children.some(c => c.name === childObj.name && c.className === childObj.className);
    if (!exists) {
      parent.children.push(childObj);
      saveSchoolParents(list);
    }
    return parent;
  }
  return null;
}

export function unlinkChildFromParent(parentId, childName) {
  const list = loadSchoolParents();
  const idx = list.findIndex(p => p.id === parentId);
  if (idx !== -1) {
    list[idx].children = (list[idx].children || []).filter(c => c.name !== childName);
    saveSchoolParents(list);
    return list[idx];
  }
  return null;
}

export function generateLoginFromName(fullName) {
  if (!fullName) return "ota.ona." + Math.floor(100 + Math.random() * 900);
  const parts = fullName.toLowerCase().trim().split(/\s+/);
  if (parts.length >= 2) {
    return `${parts[0]}.${parts[1]}.ota`;
  }
  return `${parts[0]}.ota`;
}

export function findParentByLoginOrPhone(identifier) {
  if (!identifier) return null;
  const list = loadSchoolParents();
  const clean = identifier.trim().toLowerCase();
  const digits = identifier.replace(/\D/g, "");

  return (
    list.find((p) => {
      const pLogin = (p.login || "").toLowerCase().trim();
      const pPhoneDigits = (p.phone || "").replace(/\D/g, "");
      return (
        pLogin === clean ||
        (digits && digits.length >= 7 && pPhoneDigits.includes(digits))
      );
    }) || null
  );
}

export function authenticateParent(identifier, password) {
  const parent = findParentByLoginOrPhone(identifier);
  if (!parent) {
    return {
      found: false,
      message: "Ota-ona topilmadi",
    };
  }

  // Faollik holatini tekshirish (Real boshqaruv)
  if (
    parent.isActive === false ||
    parent.status === "inactive" ||
    parent.status === "archived"
  ) {
    return {
      found: true,
      success: false,
      isBlocked: true,
      parent,
      message:
        "Hisobingiz nofaol holatda. Iltimos, ma'muriyatga murojaat qiling!",
    };
  }

  // Faol bo'lsa, oxirgi kirish vaqtini yangilash
  const now = new Date();
  const pad = (n) => String(n).padStart(2, "0");
  const formattedTime = `${pad(now.getDate())}/${pad(
    now.getMonth() + 1
  )}/${now.getFullYear()} ${pad(now.getHours())}:${pad(now.getMinutes())}`;
  updateSchoolParent(parent.id, { lastLogin: formattedTime });

  return {
    found: true,
    success: true,
    isBlocked: false,
    parent,
    message: "Xush kelibsiz!",
  };
}
